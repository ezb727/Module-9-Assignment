public class Homework09 {
    
    // ToDo 01:  Write an algorithm to solve the following problem
    /*
    The sequence of triangle numbers is generated by adding the natural numbers. So the 7th triangle number would be 1 + 2 + 3 + 4 + 5 + 6 + 7 = 28. The first ten terms would be:

1, 3, 6, 10, 15, 21, 28, 36, 45, 55, ...

Let us list the factors of the first seven triangle numbers:

 1: 1
 3: 1,3
 6: 1,2,3,6
10: 1,2,5,10
15: 1,3,5,15
21: 1,3,7,21
28: 1,2,4,7,14,28
We can see that 28 is the first triangle number to have over five divisors.

What is the value of the first triangle number to have over one hundred divisors?
    Ethan Baum - its triangle 73920
    */

    public static void main(String[] args) {
        long triangle = 0;

        for (long n = 1; ; n++) {
            triangle += n;
            int divisors = 0;

            for (long i = 1; i * i <= triangle; i++) {
                if (triangle % i == 0) {
                    divisors += (i * i == triangle) ? 1 : 2;
                }
            }

            if (divisors > 100) {
                System.out.println(triangle);
                break;
            }
        }
    }
}
